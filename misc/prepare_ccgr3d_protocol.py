#!/usr/bin/env python3
"""Prepare deterministic OpenGait partitions and manifests for CCGR-3D.

The released paper specifies a random 115/86 identity split but does not
publish the sampled identities.  We therefore publish the seed and exact ID
lists generated by this script.  It does not duplicate the RGB dataset.
"""
import argparse
import json
import random
from collections import Counter, defaultdict
from pathlib import Path


VIEWS = ("0_75", "90_0", "120_25", "150_60", "270_40")


def records(root: Path):
    output = []
    for path in sorted(root.glob("*/*/*.avi/*-rgbs.pkl")):
        view_dir = path.parent
        output.append({
            "pid": view_dir.parents[1].name,
            "condition": view_dir.parents[0].name,
            "view": view_dir.name.removesuffix(".avi"),
            "rgb": str(path.resolve()),
        })
    return output


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--rgb-root", default="/data4/CCGR_3D/RGB")
    parser.add_argument("--output-dir", default="datasets/CCGR3D")
    parser.add_argument("--seed", type=int, default=20260812)
    parser.add_argument("--train-ids", type=int, default=115)
    args = parser.parse_args()

    root = Path(args.rgb_root)
    out = Path(args.output_dir)
    out.mkdir(parents=True, exist_ok=True)
    recs = records(root)
    if not recs:
        raise FileNotFoundError(f"No CCGR-3D RGB pickles found below {root}")

    ids = sorted({r["pid"] for r in recs}, key=int)
    if len(ids) != 201:
        print(f"[Warning] expected 201 released IDs, found {len(ids)}")
    rng = random.Random(args.seed)
    train = sorted(rng.sample(ids, args.train_ids), key=int)
    test = sorted(set(ids) - set(train), key=int)

    partition = {
        "PROTOCOL": "paper-style 115/86 split; exact paper random IDs unavailable",
        "SEED": args.seed,
        "TRAIN_SET": train,
        "TEST_SET": test,
    }
    (out / "CCGR3D.json").write_text(json.dumps(partition, indent=2) + "\n")
    train_extract = dict(partition)
    train_extract["TRAIN_SET"] = []
    train_extract["TEST_SET"] = train
    (out / "CCGR3D_train_as_test.json").write_text(json.dumps(train_extract, indent=2) + "\n")

    split = {pid: "train" for pid in train} | {pid: "test" for pid in test}
    for r in recs:
        r["split"] = split[r["pid"]]
    with (out / "manifest.jsonl").open("w") as f:
        for r in recs:
            f.write(json.dumps(r) + "\n")

    groups = defaultdict(set)
    for r in recs:
        groups[(r["pid"], r["condition"])].add(r["view"])
    stats = {
        "identities": len(ids),
        "train_identities": len(train),
        "test_identities": len(test),
        "sequences": len(recs),
        "view_counts": Counter(r["view"] for r in recs),
        "complete_five_view_groups": sum(set(VIEWS).issubset(v) for v in groups.values()),
    }
    (out / "protocol_stats.json").write_text(json.dumps(stats, indent=2) + "\n")
    print(json.dumps(stats, indent=2))
    print(f"Wrote protocol files to {out.resolve()}")


if __name__ == "__main__":
    main()
